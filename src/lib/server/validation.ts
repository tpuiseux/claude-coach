import type {
  AthleteZones,
  Sport,
  UnitPreferences,
  Workout,
  WorkoutType,
} from "../../schema/training-plan.js";
import { FEELINGS, type Feeling } from "../trainingLog.js";

/**
 * Hand-rolled request-body validation for the plan mutation routes (no zod
 * in this project). Each validator either returns a clean value built only
 * from the fields it knows about, or throws ValidationError - whose message
 * the routes turn into a 400.
 *
 * The point isn't full schema validation: it's that nothing a client sends
 * can overwrite a workout's identity (id/completed), or land a value of the
 * wrong type that later crashes a reader (the Garmin/ICS/FIT exports parse
 * these fields and assume their declared types).
 */

export class ValidationError extends Error {}

const SPORTS: readonly Sport[] = ["swim", "bike", "run", "strength", "brick", "race", "rest"];
const WORKOUT_TYPES: readonly WorkoutType[] = [
  "rest",
  "recovery",
  "endurance",
  "tempo",
  "threshold",
  "intervals",
  "vo2max",
  "sprint",
  "race",
  "brick",
  "technique",
  "openwater",
  "hills",
  "long",
];

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;
// "5:07/km", "8:15/mi", "1:45/100m", or a bare "5:07". Seconds aren't
// capped at 59: settings.ts's secondsToPace can round up to "4:60", which
// every pace parser here still reads correctly.
const PACE = /^\d{1,2}:\d{2}(\/(km|mi|100m|100yd))?$/;

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isFiniteNumber(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value);
}

/** Parses a request's JSON body, turning malformed JSON into a ValidationError (400) rather than a 500. */
export async function readJsonBody(request: Request): Promise<unknown> {
  try {
    return await request.json();
  } catch {
    throw new ValidationError("Request body must be valid JSON");
  }
}

export function isIsoDate(value: unknown): value is string {
  return typeof value === "string" && ISO_DATE.test(value) && !isNaN(Date.parse(value));
}

// ---------------------------------------------------------------------------
// Workouts
// ---------------------------------------------------------------------------

type FieldCheck = (value: unknown) => boolean;

const isString: FieldCheck = (v) => typeof v === "string";
const isNonNegative: FieldCheck = (v) => isFiniteNumber(v) && v >= 0;

/** Fields a client may set on a workout. Notably absent: `id` and
 * `completed` (server-owned - completion goes through the toggle-complete
 * action) and `structure` (generated by the coach skill, not editable in
 * the UI, and too deep to validate usefully here). */
const EDITABLE_WORKOUT_FIELDS: Record<string, FieldCheck> = {
  sport: (v) => SPORTS.includes(v as Sport),
  type: (v) => WORKOUT_TYPES.includes(v as WorkoutType),
  name: isString,
  description: isString,
  durationMinutes: isNonNegative,
  distanceMeters: isNonNegative,
  primaryZone: isString,
  humanReadable: isString,
  rpe: (v) => isFiniteNumber(v) && v >= 1 && v <= 10,
  notes: isString,
  actualDuration: isNonNegative,
  actualDistance: isNonNegative,
};

/**
 * Validates a partial workout update. Unknown fields are rejected rather
 * than silently dropped, so a client bug surfaces as a 400 instead of an
 * edit that quietly doesn't save.
 */
export function parseWorkoutUpdates(input: unknown): Partial<Workout> {
  if (!isPlainObject(input)) throw new ValidationError("updates must be an object");

  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(input)) {
    // hasOwn, not a plain lookup: "__proto__", "toString" etc. would
    // otherwise resolve through Object.prototype.
    const check = Object.hasOwn(EDITABLE_WORKOUT_FIELDS, key)
      ? EDITABLE_WORKOUT_FIELDS[key]
      : undefined;
    if (!check) throw new ValidationError(`Field "${key}" cannot be edited`);
    // JSON can't carry undefined, but null is how a client would ask to
    // clear an optional field - skip it rather than store a null.
    if (value === null) continue;
    if (!check(value)) throw new ValidationError(`Invalid value for "${key}"`);
    out[key] = value;
  }
  return out as Partial<Workout>;
}

/** Validates the body of a new workout: same field rules as an edit, plus
 * the fields every workout must have. */
export function parseNewWorkout(input: unknown): Omit<Workout, "id" | "completed"> {
  const workout = parseWorkoutUpdates(input);
  for (const required of ["sport", "type", "name"] as const) {
    if (workout[required] === undefined) {
      throw new ValidationError(`"${required}" is required`);
    }
  }
  return { description: "", ...workout } as Omit<Workout, "id" | "completed">;
}


const PREFERENCE_VALUES: Record<string, readonly string[]> = {
  swim: ["meters", "yards"],
  bike: ["kilometers", "miles"],
  run: ["kilometers", "miles"],
  firstDayOfWeek: ["monday", "sunday"],
};

/** Known keys must hold one of their allowed values; unknown keys (some
 * plans carry extras, e.g. a "ski" unit) are kept as long as they're
 * strings. Not every known key is required - older plans omit some. */
export function parsePreferences(input: unknown): UnitPreferences {
  if (!isPlainObject(input)) throw new ValidationError("preferences must be an object");

  for (const [key, value] of Object.entries(input)) {
    if (typeof value !== "string") {
      throw new ValidationError(`preferences.${key} must be a string`);
    }
    const allowed = Object.hasOwn(PREFERENCE_VALUES, key) ? PREFERENCE_VALUES[key] : undefined;
    if (allowed && !allowed.includes(value)) {
      throw new ValidationError(`Invalid value for preferences.${key}`);
    }
  }
  return input as unknown as UnitPreferences;
}

// null counts as absent: the Settings UI computes some of these (e.g. a
// percentage of an unset threshold), and NaN serializes to null in JSON.
function checkOptionalNumbers(obj: Record<string, unknown>, path: string, keys: string[]): void {
  for (const key of keys) {
    if (obj[key] !== undefined && obj[key] !== null && !isFiniteNumber(obj[key])) {
      throw new ValidationError(`${path}.${key} must be a number`);
    }
  }
}

function checkZoneList(
  value: unknown,
  path: string,
  check: (zone: Record<string, unknown>, at: string) => void
): void {
  if (value === undefined) return;
  if (!Array.isArray(value)) throw new ValidationError(`${path} must be an array`);
  value.forEach((zone, i) => {
    const at = `${path}[${i}]`;
    if (!isPlainObject(zone)) throw new ValidationError(`${at} must be an object`);
    if (zone.name !== undefined && typeof zone.name !== "string") {
      throw new ValidationError(`${at}.name must be a string`);
    }
    check(zone, at);
  });
}

function optionalObject(parent: Record<string, unknown>, key: string, path: string) {
  const value = parent[key];
  if (value === undefined) return undefined;
  if (!isPlainObject(value)) throw new ValidationError(`${path}.${key} must be an object`);
  return value;
}

/**
 * Structural check of the zones object: every level that's present must
 * be the right shape, and every pace string must actually parse - the
 * Garmin export converts these to speeds, so "abc" here would push a
 * workout with NaN targets.
 */
export function parseZones(input: unknown): AthleteZones {
  if (!isPlainObject(input)) throw new ValidationError("zones must be an object");
  checkOptionalNumbers(input, "zones", ["maxHR", "restingHR", "weight"]);

  const checkPace = (zone: Record<string, unknown>, at: string, keys: string[]) => {
    for (const key of keys) {
      if (zone[key] !== undefined && !(typeof zone[key] === "string" && PACE.test(zone[key]))) {
        throw new ValidationError(`${at}.${key} is not a valid pace`);
      }
    }
  };

  const run = optionalObject(input, "run", "zones");
  if (run) {
    const hr = optionalObject(run, "hr", "zones.run");
    if (hr) {
      checkOptionalNumbers(hr, "zones.run.hr", ["lthr"]);
      checkZoneList(hr.zones, "zones.run.hr.zones", (z, at) =>
        checkOptionalNumbers(z, at, ["percentLow", "percentHigh", "hrLow", "hrHigh"])
      );
    }
    const pace = optionalObject(run, "pace", "zones.run");
    if (pace) {
      checkOptionalNumbers(pace, "zones.run.pace", ["thresholdPaceSeconds"]);
      checkPace(pace, "zones.run.pace", ["thresholdPace"]);
      checkZoneList(pace.zones, "zones.run.pace.zones", (z, at) => {
        if (z.zone !== undefined && typeof z.zone !== "string") {
          throw new ValidationError(`${at}.zone must be a string`);
        }
        checkOptionalNumbers(z, at, ["paceSeconds"]);
        checkPace(z, at, ["pace", "low", "high"]);
      });
    }
  }

  const bike = optionalObject(input, "bike", "zones");
  if (bike) {
    const hr = optionalObject(bike, "hr", "zones.bike");
    if (hr) {
      checkOptionalNumbers(hr, "zones.bike.hr", ["lthr"]);
      checkZoneList(hr.zones, "zones.bike.hr.zones", (z, at) =>
        checkOptionalNumbers(z, at, ["percentLow", "percentHigh", "hrLow", "hrHigh"])
      );
    }
    const power = optionalObject(bike, "power", "zones.bike");
    if (power) {
      checkOptionalNumbers(power, "zones.bike.power", ["ftp"]);
      checkZoneList(power.zones, "zones.bike.power.zones", (z, at) =>
        checkOptionalNumbers(z, at, ["percentLow", "percentHigh", "wattsLow", "wattsHigh"])
      );
    }
  }

  const swim = optionalObject(input, "swim", "zones");
  if (swim) {
    checkOptionalNumbers(swim, "zones.swim", ["cssSeconds"]);
    checkPace(swim, "zones.swim", ["css"]);
    checkZoneList(swim.zones, "zones.swim.zones", (z, at) => {
      checkOptionalNumbers(z, at, ["paceOffset"]);
      checkPace(z, at, ["pace"]);
    });
  }

  return input as AthleteZones;
}

